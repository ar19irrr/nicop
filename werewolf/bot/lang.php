// 4. تابع دریافت توضیحات نقش
// ============================================================

function getRoleDescription($role) {
    global $lang;
    
    $key = 'role_' . $role;
    
    if (isset($lang[$key])) {
        return $lang[$key];
    }
    
    return "🎭 شما " . getRoleDisplayName($role) . " هستید!";
}

