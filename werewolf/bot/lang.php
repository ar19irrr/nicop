// 3. تابع دریافت پیام با جایگزینی متغیرها
// ============================================================

function getLang($key, $replace = []) {
    global $lang;
    
    if (!isset($lang[$key])) {
        return "❌ پیام یافت نشد: $key";
    }
    
    $message = $lang[$key];
    
    foreach ($replace as $search => $replace_value) {
        $message = str_replace('{' . $search . '}', $replace_value, $message);
    }
    
    return $message;
}

